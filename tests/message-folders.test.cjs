const {test}=require('node:test');
const assert=require('node:assert/strict');
const fs=require('node:fs'),os=require('node:os'),path=require('node:path');
const {once}=require('node:events');
const {createGalleryServer}=require('../server.cjs');
test('Message folders: private spam/trash, restore, unread counts, persistence and explicit purge',async()=>{
 const dir=fs.mkdtempSync(path.join(os.tmpdir(),'message-folders-'));
 let server,base,cookie='';
 const start=async()=>{server=createGalleryServer({dataDir:dir,uploadDir:path.join(dir,'images'),exportFile:path.join(dir,'gallery-data.js'),mailDisabled:true});server.listen(0,'127.0.0.1');await once(server,'listening');base='http://127.0.0.1:'+server.address().port;};
 const stop=()=>new Promise(r=>server.close(r));
 const call=(url,method='GET',data,auth=true)=>fetch(base+url,{method,headers:{Origin:base,'Content-Type':'application/json',...(auth?{Cookie:cookie}:{})},body:data===undefined?undefined:JSON.stringify(data)});
 const login=async(setup)=>{const r=await call('/api/auth/'+(setup?'setup':'login'),'POST',{username:'admin',password:'Disposable-message-folders-2026'});cookie=r.headers.get('set-cookie').split(';')[0];};
 const inbox=async folder=>(await call('/api/messages?folder='+folder)).json();
 try{
  await start();await login(true);
  const item={requestId:crypto.randomUUID(),email:'sample@example.com',category:'it',details:'web',message:'Test prywatnej wiadomości i folderów.'};
  assert.equal((await call('/api/contact','POST',item,false)).status,201);
  const url='/api/messages/'+item.requestId;
  assert.equal((await call(url,'PUT',{folder:'spam'},false)).status,401);
  assert.equal((await inbox('inbox')).unread,1);
  assert.equal((await call(url,'PUT',{folder:'invalid'})).status,400);
  assert.equal((await call(url,'PUT',{folder:'spam'})).status,200);
  assert.equal((await inbox('inbox')).items.length,0);assert.equal((await inbox('inbox')).unread,0);
  let spam=await inbox('spam');assert.equal(spam.items[0].message,item.message);assert.equal(spam.counts.spam,1);
  assert.equal((await call('/api/messages?folder=spam','GET',undefined,false)).status,401);
  await stop();await start();await login(false);
  assert.equal((await inbox('spam')).items[0].id,item.requestId);
  assert.equal((await call(url,'DELETE',{confirmId:item.requestId})).status,400);
  assert.equal((await call(url,'PUT',{folder:'inbox'})).status,200);
  assert.equal((await inbox('inbox')).unread,1);
  assert.equal((await call(url,'PUT',{folder:'trash'})).status,200);
  assert.equal((await inbox('trash')).items.length,1);
  assert.equal((await call(url,'DELETE',{})).status,400);
  assert.equal((await call(url,'DELETE',{confirmId:item.requestId},false)).status,401);
  assert.equal((await call(url,'DELETE',{confirmId:item.requestId})).status,200);
  assert.equal((await inbox('trash')).items.length,0);
  assert.equal((await call(url,'PUT',{folder:'inbox'})).status,404);
  const add = async(folder)=>{const row={...item,requestId:crypto.randomUUID()};assert.equal((await call('/api/contact','POST',row,false)).status,201);if(folder!=='inbox')await call('/api/messages/'+row.requestId,'PUT',{folder});return row;};
  await add('inbox');await add('trash');
  const before=await inbox('trash');
  await add('trash');
  const payload={folder:'trash',confirmation:'EMPTY_TRASH',snapshot:before.snapshot};
  assert.equal((await call('/api/messages','DELETE',payload)).status,409);
  const latest=await inbox('trash');payload.snapshot=latest.snapshot;
  assert.equal((await call('/api/messages','DELETE',payload,false)).status,401);
  const emptied=await call('/api/messages','DELETE',payload);assert.equal(emptied.status,200);assert.equal((await emptied.json()).deleted,2);
  assert.equal((await inbox('trash')).items.length,0);assert.equal((await inbox('inbox')).items.length,1);
 }finally{if(server?.listening)await stop();fs.rmSync(dir,{recursive:true,force:true});}
});
